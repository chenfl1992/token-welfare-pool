#!/usr/bin/env node
// 交互式生成部署配置。--defaults 用于一键安装（全部采用推荐值）。
import readline from 'node:readline/promises';
import { stdin as input, stdout as output, execPath, platform } from 'node:process';
import path from 'node:path';
import {
  ROOT, CONFIG_PATH, FREAPI_DIR, writeJson, writeText,
} from './lib.mjs';

const args = process.argv.slice(2);
const quick = args.includes('--defaults') || args.includes('-y') || !input.isTTY;
const rl = quick ? null : readline.createInterface({ input, output });

async function ask(label, defaultValue) {
  if (quick) { console.log(`  ${label} = ${defaultValue} (默认)`); return defaultValue; }
  const answer = (await rl.question(`  ${label} [${defaultValue}]: `)).trim();
  return answer === '' ? defaultValue : answer;
}

async function yes(label, defaultValue = true) {
  const hint = defaultValue ? 'Y/n' : 'y/N';
  const answer = await ask(`${label} (${hint})`, defaultValue ? 'y' : 'n');
  return /^(y|yes|1|true)$/i.test(answer);
}

function port(value) {
  const n = Number(value);
  if (!Number.isInteger(n) || n < 1 || n > 65535) throw new Error(`无效端口: ${value}`);
  return n;
}

console.log('\nToken 福利铺 — 部署配置向导');
console.log('直接回车采用默认值。配置只保存在本机，不会随仓库上传。\n');

const apiPort = port(await ask('freellmapi 监听端口', '3001'));
const host = await ask('监听地址（127.0.0.1=仅本机，0.0.0.0=局域网）', '127.0.0.1');
const ofmEnabled = await yes('启用 OFM 免费网关（提供 DSH 渠道）');
const ofmPort = ofmEnabled ? port(await ask('OFM 网关端口', '18899')) : null;
const tunnelMode = (await ask('公网隧道 off / quick / named', 'off')).toLowerCase();
if (!['off', 'quick', 'named'].includes(tunnelMode)) throw new Error('隧道模式只能是 off / quick / named');
const tunnelName = tunnelMode === 'named' ? await ask('Cloudflare 隧道名称', 'tokenpool') : '';
const tunnelConfig = tunnelMode === 'named'
  ? await ask('cloudflared 配置文件绝对路径', path.join(ROOT, 'config', 'tunnel.yml'))
  : '';
const autostart = await yes('注册开机自启', true);

const config = {
  version: 1,
  generatedAt: new Date().toISOString(),
  platform,
  nodeBin: execPath,
  installDir: ROOT,
  apiPort,
  host,
  ofmEnabled,
  ofmPort,
  ofmDataDir: path.join(ROOT, 'ofm-data'),
  tunnelMode,
  tunnelName,
  tunnelConfig,
  publicUrl: '',
  autostart,
};

writeJson(CONFIG_PATH, config);

const env = [
  '# Generated by bootstrap/setup.mjs — 修改后需重启服务',
  `PORT=${apiPort}`,
  `HOST=${host}`,
  `DSH_GATEWAY_URL=http://127.0.0.1:${ofmPort ?? 18899}/v1`,
  '',
].join('\n');
writeText(path.join(FREAPI_DIR, '.env'), env);

if (rl) rl.close();

console.log('\n✓ 配置已写入 config/deployment.json');
console.log(`✓ 环境变量已写入 apps/freellmapi/.env (端口 ${apiPort}, 主机 ${host})`);
console.log('\n下一步：');
console.log('  1) 启动服务：node bootstrap/control.mjs start');
console.log('  2) 健康检查：node bootstrap/doctor.mjs');
console.log('  3) 登录管理页 http://127.0.0.1:' + apiPort + ' 添加免费渠道');
console.log('  4) 渠道可用后创建单入口分组：node bootstrap/seed-group.mjs\n');
